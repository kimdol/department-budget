import { expect, test } from "@playwright/test";

test("다른 탭에서 규정을 먼저 발행해도 편집 중인 후보로 다시 비교한다", async ({page,context}) => {
  await page.goto("/");
  await page.getByRole("button", {name:"개인 데모 시작"}).click();
  await page.locator("#role").selectOption("FINANCE");
  await page.locator("#policy-panel summary").click();
  const editor = page.getByRole("region", {name:"비용 지원 규정"});
  const formula = editor.getByLabel("인정액 수식");
  await formula.fill("min(eligible_cost * 0.9, event_cap)");
  await expect(editor).toContainText(/144,000.*162,000/);
  await editor.getByRole("button",{name:"검토 요청"}).click();
  await expect(editor).toContainText("검토 요청 시 실비");
  const candidate = "min(eligible_cost * support_rate, event_cap * 1.25)";
  await formula.fill(candidate);
  await editor.getByLabel("비교할 실비(원)").fill("300000");
  await expect(editor).toContainText("차이 40,000원");

  const other = await context.newPage();
  await other.goto(page.url());
  await other.locator("#role").selectOption("MANAGER");
  await other.locator("#policy-panel summary").click();
  await other.getByRole("button",{name:"발행",exact:true}).click();
  await expect(other.getByText("적용 버전 1",{exact:true})).toBeVisible();
  await other.locator("#role").selectOption("FINANCE");
  await expect(other.getByRole("button",{name:"검토 요청"})).toBeVisible();

  await editor.getByRole("button",{name:"검토 요청"}).click();
  await expect(editor.getByRole("button",{name:"검토 요청"})).toBeDisabled();
  await editor.getByRole("button",{name:"최신 규정과 다시 비교"}).click();
  await expect(editor).toContainText("적용 버전 1");
  await expect(formula).toHaveValue(candidate);
  await expect(editor).toContainText("기존 200,000원 / 후보 240,000원 / 차이 40,000원");
  await editor.getByRole("button",{name:"검토 요청"}).click();
  await expect(editor).toContainText("검토 요청 시 실비 300,000원 · 1일 · 지원액 200,000원 → 240,000원");
});

test("병원 학회비 규정을 비교해 발행하고 과거 버전을 복구한다", async ({ page }) => {
  await page.goto("/");
  await page.getByLabel("체험 조직").selectOption("HOSPITAL");
  await page.getByRole("button", { name: "개인 데모 시작" }).click();
  await expect(page.locator("#workspace-organization")).toHaveText("병원 행정부서");
  await page.locator('#submit [name="category"]').selectOption("CONFERENCE");
  await page.getByRole("button",{name:"지원 예정액 확인"}).click();
  await expect(page.locator("#estimate-result")).toContainText("정산 준비 · 지출 영수증이 필요합니다. 병원 학회비는 참석 확인서가 필요합니다.");
  await page.locator('#submit [name="category"]').selectOption("EDUCATION");
  await page.getByRole("button",{name:"지원 예정액 확인"}).click();
  await expect(page.locator("#estimate-result")).toContainText("정산 준비 · 지출 영수증이 필요합니다.");
  await expect(page.locator("#estimate-result")).not.toContainText("참석 확인서");
  await page.locator("#role").selectOption("FINANCE");
  await page.locator("#policy-panel summary").click();
  const editor = page.getByRole("region", { name: "비용 지원 규정" });
  const attendance = editor.getByRole("region", {name:"참석 조건 미리보기"});
  await expect(attendance).toContainText("판정 결과 · 자료 부족");
  await attendance.getByLabel("비교 사례에 참석 확인서 포함").check();
  await expect(attendance).toContainText("판정 결과 · 충족");
  await attendance.getByLabel("비교할 참석 조건").fill("ALL(OUTSIDE_HOSPITAL,ATTACHED)");
  await expect(attendance).toContainText("판정 결과 · 미충족");
  await expect(attendance).toContainText("참석 확인서 제출 · 평가 생략");
  await editor.getByLabel("인정액 수식").fill("min(eligible_cost, days)");
  await expect(editor).toContainText("20번째 문자: 단위가 일치하지 않습니다.");
  await expect(editor.getByRole("button", { name: "검토 요청" })).toBeDisabled();
  await editor.getByLabel("비교할 실비(원)").fill("300000");
  await editor.getByLabel("인정액 수식").fill("eligible_cost");
  await expect(editor).toContainText("승인 경로 기존 부서장 / 후보 부서장 → 재무");
  await editor.getByLabel("비교할 실비(원)").fill("299999");
  await expect(editor.getByText("승인 경로 기존 부서장 / 후보 부서장", {exact:true})).toBeVisible();
  await editor.getByLabel("비교할 실비(원)").fill("180000");
  await editor.getByLabel("인정액 수식").fill("min(eligible_cost * 0.90, event_cap)");
  await expect(editor).toContainText(/144,000.*162,000/);
  await expect(editor).toContainText("직원 부담액 기존 36,000원 / 후보 18,000원");
  await editor.getByRole("button", { name: "검토 요청" }).click();
  await page.locator("#role").selectOption("MANAGER");
  await editor.getByLabel("비교할 실비(원)").fill("10000");
  await expect(editor).toContainText("검토 요청 시 실비 180,000원 · 1일 · 지원액 144,000원 → 162,000원");
  await expect(editor).toContainText("참석 조건 · ALL(OUTSIDE_HOSPITAL,ATTACHED)");
  await editor.getByRole("button", { name: "발행", exact: true }).click();
  await expect(editor).toContainText("적용 버전 1");
  await page.locator("#role").selectOption("FINANCE");
  await editor.getByRole("button", { name: "복구 후보로 선택" }).click();
  await expect(attendance.getByLabel("비교할 참석 조건")).toHaveValue("ANY(OUTSIDE_HOSPITAL,OTHER_CATEGORY,ATTACHED)");
  await editor.getByLabel("비교할 실비(원)").fill("180000");
  await expect(editor).toContainText(/162,000.*144,000/);
  await editor.getByRole("button", { name: "검토 요청" }).click();
  await page.locator("#role").selectOption("MANAGER");
  await editor.getByRole("button", { name: "발행", exact: true }).click();
  await expect(editor).toContainText("적용 버전 2");
  await expect(editor).toContainText("버전 1 · 평가기 decimal-v2");
  await expect(editor).toContainText("버전 2 · 평가기 decimal-v1");
  await expect(editor).toContainText(/144,000.*144,000/);
});
